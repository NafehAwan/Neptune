// Copies the Lucide line icons (ISC) the launcher uses into src/lib/lucide.ts,
// the same icons the Grove Glass mockups use. Run from tuff-client/design after
// `npm ci` there:  node ../launcher/scripts/make-lucide.mjs
import fs from "fs";

// launcher icon name -> lucide icon
const MAP = {
  home: "house", library: "library", cube: "box", server: "server", globe: "globe", shirt: "shirt", camera: "camera",
  console: "terminal", gear: "settings", play: "play", plus: "plus", folder: "folder", trash: "trash-2", edit: "pencil",
  close: "x", minimize: "minus", maximize: "square", user: "user", "user-plus": "user-plus", download: "download",
  search: "search", check: "check", chevron: "chevron-down", stop: "square", copy: "copy", refresh: "refresh-cw",
  spark: "sparkles", link: "link", bell: "bell", logout: "log-out", grid: "layout-grid",
};
const dir = new URL("../../design/node_modules/lucide-static/icons/", import.meta.url);
const out = {};
for (const [name, file] of Object.entries(MAP)) {
  const svg = fs.readFileSync(new URL(`${file}.svg`, dir), "utf8");
  out[name] = svg.replace(/<!--.*?-->/s, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
}
fs.writeFileSync(new URL("../src/lib/lucide.ts", import.meta.url),
  "// Generated by scripts/make-lucide.mjs from lucide-static (ISC). Inner SVG markup on a 24x24 grid.\n" +
  "export const LUCIDE: Record<string, string> = " + JSON.stringify(out, null, 2) + ";\n");
console.log(Object.keys(out).length, "icons");
