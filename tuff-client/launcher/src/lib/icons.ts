/** Run-length merges rows into SVG rects. */
function toRects(grid: string[], color: (c: string) => string | null): string {
  let out = "";
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const fill = color(row[x]);
      if (!fill) { x++; continue; }
      let run = 1;
      while (x + run < row.length && row[x + run] === row[x]) run++;
      out += `<rect x="${x}" y="${y}" width="${run}" height="1" fill="${fill}"/>`;
      x += run;
    }
  });
  return out;
}

const uiCache = new Map<string, string>();
export function uiIcon(name: string): string {
  let svg = uiCache.get(name);
  if (!svg) {
    const grid = ui[name] ?? ui.cube;
    svg = toRects(grid, (c) => (c === "#" ? "currentColor" : null));
    uiCache.set(name, svg);
  }
  return svg;
}

