const profileCache = new Map<string, string>();
export function profileIcon(name: string): string {
  let svg = profileCache.get(name);
  if (!svg) {
    const art = profileArt[name] ?? profileArt.grass;
    svg = toRects(art.grid, (c) => art.palette[c] ?? null);
    profileCache.set(name, svg);
  }
  return svg;
}
