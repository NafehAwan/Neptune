"""Draws two sample 64x64 Minecraft skins (standard layout, with a hat layer) and
writes them as PNGs plus skins.js (base64) for the mockups. The real client reads
the player's own skin the same way; these only stand in for it here."""
import base64
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE / "assets" / "skins"


def hexc(h, a=255):
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def paint(img, ox, oy, rows, pal):
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                img.putpixel((ox + x, oy + y), hexc(pal[ch]))


def fill(img, x, y, w, h, color):
    for j in range(h):
        for i in range(w):
            img.putpixel((x + i, y + j), hexc(color))


def body(img, shirt, shirt_dark, pants, shoes, skin):
    # torso, arms and legs (front/side/back blocks), simple but valid
    fill(img, 16, 20, 24, 12, shirt)      # torso faces
    fill(img, 20, 16, 16, 4, shirt_dark)  # torso top/bottom
    fill(img, 40, 20, 16, 12, shirt)      # right arm
    fill(img, 40, 28, 16, 4, skin)        # hands
    fill(img, 32, 52, 16, 12, shirt)      # left arm
    fill(img, 32, 60, 16, 4, skin)
    fill(img, 0, 20, 16, 12, pants)       # right leg
    fill(img, 0, 29, 16, 3, shoes)
    fill(img, 16, 52, 16, 12, pants)      # left leg
    fill(img, 16, 61, 16, 3, shoes)


def explorer():
    """Dark-haired explorer in a green hood (the signed-in sample account)."""
    img = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    pal = {"h": "#2B1E16", "H": "#3A2A1F", "s": "#D9A27E", "S": "#C98F6C", "c": "#BF8362",
           "w": "#F4F1EC", "e": "#3E7B5B", "E": "#2C5A42", "n": "#C2876A", "m": "#8E5A47",
           "g": "#2F6B4F", "G": "#24543E", "l": "#3E8A64"}
    # head base layer: top, bottom, right, front, left, back
    paint(img, 8, 0, ["hhHhhhHh", "hHhhhhhh", "hhhhHhhh", "hhhhhhhH", "Hhhhhhhh", "hhhHhhhh", "hhhhhhHh", "hHhhhhhh"], pal)
    paint(img, 16, 0, ["ssssssss"] * 8, pal)
    paint(img, 0, 8, ["hhhhhhhh", "hhhhhhhh", "hhhhhhss", "hhhhhsss", "hhhhssss", "hhhsssss", "hhhssscs", "hhhhsscc"], pal)
    paint(img, 8, 8, ["hhhhhhhh", "hHhhhhHh", "hsHhhHsh", "ssssssss", "swessews", "sssnnsss", "sssmmsss", "cssssssc"], pal)
    paint(img, 16, 8, ["hhhhhhhh", "hhhhhhhh", "sshhhhhh", "ssshhhhh", "sssshhhh", "ssssshhh", "scssshhh", "ccsshhhh"], pal)
    paint(img, 24, 8, ["hhhhhhhh", "hhHhhhhh", "hhhhhHhh", "hhhhhhhh", "hHhhhhhh", "hhhhhhHh", "hhhhhhhh", "hhhhhhhh"], pal)
    # hat layer: a hood framing the face
    paint(img, 40, 0, ["gGgglggg", "gggggGgg", "glgggggg", "ggggGggl", "gGgggggg", "ggglgggG", "gggggggg", "Gggggglg"], pal)
    paint(img, 32, 8, ["gglggggg", "gggggglg", "gGgggggg", "ggggglgg", "gggGgggg", "Ggggggg.", "GGgggg..", "GGGGGG.."], pal)
    paint(img, 40, 8, ["glgggggg", "gHhhHhhg", "g.h..h.g", "g......g", "G......G", "G......G", "G......G", "GG....GG"], pal)
    paint(img, 48, 8, ["gggglggg", "glgggggg", "ggggggGg", "gglggggg", "ggggGggg", ".gggggGG", "..ggggGG", "..GGGGGG"], pal)
    paint(img, 56, 8, ["gggggggg", "gggglggg", "gggggggg", "gggggggg", "ggGggggg", "gggggggg", "GGgggggG", "GGGGGGGG"], pal)
    body(img, "#2F6B4F", "#24543E", "#3B3F4A", "#2A2522", "#D9A27E")
    return img


def default():
    """A plain default-style head (stands in for the game's built-in default skin)."""
    img = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    pal = {"h": "#4A3222", "H": "#3A2618", "s": "#C99B7B", "S": "#B98B6C", "c": "#AF7F60",
           "w": "#F2F2F2", "e": "#4361A8", "n": "#9E6C52", "m": "#7A4E3B", "b": "#6A4532"}
    paint(img, 8, 0, ["hhhhhhhh", "hHhhhhHh", "hhhhhhhh", "hhhHhhhh", "hhhhhhhh", "hHhhhhhh", "hhhhhHhh", "hhhhhhhh"], pal)
    paint(img, 16, 0, ["ssssssss"] * 8, pal)
    paint(img, 0, 8, ["hhhhhhhh", "hhhhhhhh", "hhhhhhss", "hhhhssss", "hhssssss", "ssssssss", "ssssscss", "sssssccs"], pal)
    paint(img, 8, 8, ["hhhhhhhh", "hhhhhhhh", "hssssssh", "ssssssss", "swessews", "sssnnsss", "ssbmmbss", "ssbbbbss"], pal)
    paint(img, 16, 8, ["hhhhhhhh", "hhhhhhhh", "sshhhhhh", "sssshhhh", "sssssshh", "ssssssss", "sscsssss", "sccsssss"], pal)
    paint(img, 24, 8, ["hhhhhhhh", "hhhhhhhh", "hhhhhhhh", "hhhhhhhh", "hhhhhhhh", "hHhhhhhh", "hhhhhhhh", "hhhhhhhh"], pal)
    body(img, "#3BA8A0", "#2E8A83", "#3E4A8C", "#5A5A5A", "#C99B7B")
    return img


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    data = {}
    for name, fn in (("explorer", explorer), ("default", default)):
        path = OUT / f"{name}.png"
        fn().save(path)
        data[name] = "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode()
    js = "// Generated by make-skins.py: sample 64x64 skins as data URLs.\nwindow.SKIN_DATA = " + repr(data).replace("'", '"') + ";\n"
    (HERE / "skins.js").write_text(js)
    print("wrote", ", ".join(data))
